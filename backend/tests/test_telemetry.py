def test_telemetry_spans_carry_required_resource_attributes():
    """Verify spans generated by the tracer carry service name, environment, and version on their Resource."""
    test_resource = create_telemetry_resource(
        service_name="test-telemetry-service",
        environment="test-env",
        deployed_version="9.9.9",
    )

    provider = TracerProvider(resource=test_resource)
    exporter = InMemorySpanExporter()
    provider.add_span_processor(SimpleSpanProcessor(exporter))

    tracer = provider.get_tracer("test-tracer")
    with tracer.start_as_current_span("unit-test-span") as span:
        span.set_attribute("test.key", "test-val")

    spans = exporter.get_finished_spans()
    assert len(spans) == 1
    finished = spans[0]
    assert finished.name == "unit-test-span"

    res_attrs = finished.resource.attributes
    assert res_attrs[SERVICE_NAME] == "test-telemetry-service"
    assert res_attrs[SERVICE_VERSION] == "9.9.9"
    assert res_attrs["deployment.environment"] == "test-env"
    assert res_attrs["environment"] == "test-env"
    assert res_attrs["deployed_version"] == "9.9.9"


def test_fastapi_http_request_span_attributes():
    """Verify FastAPI requests generate telemetry spans with service name, environment, and deployed version attributes."""
    from fastapi import FastAPI
    from opentelemetry.instrumentation.fastapi import FastAPIInstrumentor

    custom_resource = create_telemetry_resource(
        service_name="economic-dashboard-backend-test",
        environment="testing",
        deployed_version="0.1.0-test",
    )

    exporter = InMemorySpanExporter()
    provider = TracerProvider(resource=custom_resource)
    provider.add_span_processor(SimpleSpanProcessor(exporter))

    test_app = FastAPI()

    def server_request_hook(span, scope):
        if span and span.is_recording():
            span.set_attribute("service.name", "economic-dashboard-backend-test")
            span.set_attribute("environment", "testing")
            span.set_attribute("deployment.environment", "testing")
            span.set_attribute("deployed_version", "0.1.0-test")
            span.set_attribute("service.version", "0.1.0-test")

    FastAPIInstrumentor.instrument_app(
        test_app,
        tracer_provider=provider,
        server_request_hook=server_request_hook,
    )

    @test_app.get("/health")
    def health():
        return {"status": "ok"}

    client = TestClient(test_app)
    response = client.get("/health")
    assert response.status_code == 200

    spans = exporter.get_finished_spans()
    assert len(spans) > 0

    # Locate the server request span
    req_spans = [s for s in spans if s.name in ("GET /health", "/health", "GET /health http send")]
    assert len(req_spans) > 0

    target_span = next((s for s in req_spans if "service.name" in s.attributes), req_spans[0])
    # Check that resource attributes are present
    assert target_span.resource.attributes.get("service.name") == "economic-dashboard-backend-test"
    assert target_span.resource.attributes.get("deployment.environment") == "testing"
    assert target_span.resource.attributes.get("service.version") == "0.1.0-test"

    # Check span-level attributes
    server_span = next(s for s in req_spans if s.name in ("GET /health", "/health"))
    assert server_span.attributes.get("service.name") == "economic-dashboard-backend-test"
    assert server_span.attributes.get("environment") == "testing"
    assert server_span.attributes.get("deployed_version") == "0.1.0-test"


def test_system_status_and_telemetry_endpoints(client: TestClient):
    """Verify /api/system/status and /api/system/telemetry return expected telemetry identity fields."""
    # Test /api/system/status
    res_status = client.get("/api/system/status")
    assert res_status.status_code == 200
    data_status = res_status.json()

    assert "telemetry" in data_status
    telemetry = data_status["telemetry"]
    assert "service_name" in telemetry
    assert "environment" in telemetry
    assert "deployed_version" in telemetry
    assert len(telemetry["service_name"]) > 0
    assert len(telemetry["environment"]) > 0
    assert len(telemetry["deployed_version"]) > 0

    # Test /api/system/telemetry
    res_tel = client.get("/api/system/telemetry")
    assert res_tel.status_code == 200
    data_tel = res_tel.json()
    assert data_tel["service_name"] == telemetry["service_name"]
    assert data_tel["environment"] == telemetry["environment"]
    assert data_tel["deployed_version"] == telemetry["deployed_version"]
